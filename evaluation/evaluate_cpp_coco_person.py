"""Evaluate C++ COCO person predictions with the shared COCOeval pipeline."""

import argparse
import json
import platform
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import pycocotools
from pycocotools.coco import COCO
from pycocotools.cocoeval import COCOeval


PROJECT_ROOT = Path(__file__).resolve().parents[1]
ANNOTATION_FILE = (
    PROJECT_ROOT / "datasets/coco/annotations/instances_val2017.json"
)
COCO_PERSON_CATEGORY_ID = 1


def parse_args() -> argparse.Namespace:
    """Parse the optional smoke-test image limit."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--limit",
        type=int,
        help="Evaluate predictions for only the first N COCO image IDs.",
    )
    return parser.parse_args()


def load_json(path: Path) -> Any:
    """Load one required JSON artifact."""
    if not path.is_file():
        raise FileNotFoundError(f"JSON file not found: {path}")
    with path.open(encoding="utf-8") as file:
        return json.load(file)


def evaluate(args: argparse.Namespace) -> None:
    """Run COCOeval on predictions generated by the C++ executable."""
    if args.limit is not None and args.limit <= 0:
        raise ValueError("--limit must be positive")

    coco_ground_truth = COCO(str(ANNOTATION_FILE))
    image_ids = sorted(coco_ground_truth.getImgIds())
    if args.limit is not None:
        image_ids = image_ids[: args.limit]
    suffix = "" if args.limit is None else f"_{len(image_ids)}_images"

    prediction_file = (
        PROJECT_ROOT
        / "outputs/yolo11n"
        / f"cpp_coco_val2017_person_predictions{suffix}.json"
    )
    metrics_file = (
        PROJECT_ROOT
        / "results/yolo11n"
        / f"cpp_coco_person_metrics{suffix}.json"
    )

    predictions = load_json(prediction_file)
    cpp_metrics = load_json(metrics_file)
    if not isinstance(predictions, list) or not predictions:
        raise ValueError("The C++ prediction file contains no predictions")

    coco_predictions = coco_ground_truth.loadRes(str(prediction_file))
    evaluator = COCOeval(coco_ground_truth, coco_predictions, "bbox")
    evaluator.params.imgIds = image_ids
    evaluator.params.catIds = [COCO_PERSON_CATEGORY_ID]
    evaluator.evaluate()
    evaluator.accumulate()
    evaluator.summarize()

    stats = evaluator.stats
    metrics = {
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "model": {
            "name": "yolo11n",
            "path": "models/yolo11n/yolo11n.onnx",
            "input_size": int(cpp_metrics["model"]["input_size"]),
            "runtime": cpp_metrics["model"]["runtime"],
        },
        "dataset": {
            "name": "COCO val2017",
            "images": len(image_ids),
            "category": "person",
            "category_id": COCO_PERSON_CATEGORY_ID,
        },
        "evaluation": {
            "confidence_threshold": float(
                cpp_metrics["evaluation"]["confidence_threshold"]
            ),
            "nms_iou_threshold": float(
                cpp_metrics["evaluation"]["nms_iou_threshold"]
            ),
            "max_detections": int(
                cpp_metrics["evaluation"]["max_detections"]
            ),
            "predictions": len(predictions),
            "ap_50_95": float(stats[0]),
            "ap_50": float(stats[1]),
            "ap_75": float(stats[2]),
            "ap_small": float(stats[3]),
            "ap_medium": float(stats[4]),
            "ap_large": float(stats[5]),
            "ar_1": float(stats[6]),
            "ar_10": float(stats[7]),
            "ar_100": float(stats[8]),
            "ar_small": float(stats[9]),
            "ar_medium": float(stats[10]),
            "ar_large": float(stats[11]),
        },
        "performance": {
            "device": "cpu",
            "warmup_iterations": int(
                cpp_metrics["performance"]["warmup_iterations"]
            ),
            "wall_time_seconds": float(
                cpp_metrics["performance"]["wall_time_seconds"]
            ),
            "throughput_images_per_second": float(
                cpp_metrics["performance"]["throughput_images_per_second"]
            ),
            "mean_inference_ms": float(
                cpp_metrics["performance"]["mean_inference_ms"]
            ),
            "p50_inference_ms": float(
                cpp_metrics["performance"]["p50_inference_ms"]
            ),
            "p95_inference_ms": float(
                cpp_metrics["performance"]["p95_inference_ms"]
            ),
        },
        "environment": {
            "platform": platform.platform(),
            "onnxruntime": cpp_metrics["environment"]["onnxruntime"],
            "opencv_cpp": cpp_metrics["environment"]["opencv_cpp"],
            "pycocotools": getattr(pycocotools, "__version__", "unknown"),
        },
    }

    metrics_file.parent.mkdir(parents=True, exist_ok=True)
    with metrics_file.open("w", encoding="utf-8") as file:
        json.dump(metrics, file, indent=2)
        file.write("\n")
    print(f"\nMetrics summary: {metrics_file}")


def main() -> None:
    """Run the C++ prediction evaluator."""
    evaluate(parse_args())


if __name__ == "__main__":
    main()
